import type { ToolId } from "@/data/tools";

export type DraftFormValues = Record<string, string>;

/**
 * Generates a draft for the given tool from the given form values.
 *
 * This is currently a local templated placeholder (no network call, small
 * artificial delay to simulate generation). Swap the body of this function
 * for a real API call (e.g. `await fetch("/api/generate", { method: "POST",
 * body: JSON.stringify({ toolId, values }) })`) once a real AI backend is
 * wired up — the calling code (DraftGenerator) already awaits this function
 * and handles loading/error state, so no UI changes should be required.
 */
export async function generateDraft(
  toolId: ToolId,
  values: DraftFormValues
): Promise<string> {
  await new Promise((resolve) => setTimeout(resolve, 900));
  return buildTemplateDraft(toolId, values);
}

function buildTemplateDraft(toolId: ToolId, values: DraftFormValues): string {
  switch (toolId) {
    case "cv":
      return buildCvDraft(values);
    case "sop":
      return buildSopDraft(values);
    case "lor":
      return buildLorDraft(values);
    default:
      return "";
  }
}

function pick(values: DraftFormValues, id: string, fallback: string) {
  const v = values[id]?.trim();
  return v && v.length > 0 ? v : fallback;
}

// Strips a single trailing sentence-ending punctuation mark so the value can
// be safely embedded mid-sentence without producing a doubled "..".
function pickSentence(values: DraftFormValues, id: string, fallback: string) {
  return pick(values, id, fallback).replace(/[.!?]+$/, "");
}

function buildCvDraft(values: DraftFormValues): string {
  const program = pick(values, "targetProgram", "your target program");
  const university = values.university?.trim();
  const field = pick(values, "field", "your field");
  const background = pick(
    values,
    "background",
    "Add your degree, coursework, projects and skills here."
  );

  return `FUTURE GRAD STUDENT
Applicant — ${program}${university ? ` · ${university}` : ""}

EDUCATION & BACKGROUND
${background}

FIELD OF INTEREST
${field}

CORE SKILLS
Communication · Problem-solving · Project management · (add role-specific tools & languages)

— This is a placeholder draft generated by a template, not a real AI model.
Connect a real generation backend to produce a personalized version. —`;
}

function buildSopDraft(values: DraftFormValues): string {
  const program = pick(values, "program", "your target program");
  const university = pick(values, "university", "your target university");
  const field = pick(values, "field", "your field");
  const motivation = pickSentence(
    values,
    "motivation",
    "explain what draws you to this field and this specific program"
  );
  const background = pickSentence(
    values,
    "background",
    "describe your relevant academic and professional background"
  );

  return `Statement of Purpose

I am writing to express my strong interest in the ${program} at ${university}. My interest in ${field} has grown out of both academic curiosity and hands-on experience, and I believe this program is the right next step in that journey.

Specifically, ${motivation}. This experience clarified the kind of researcher and professional I want to become, and it is why I am drawn to ${university}'s approach to ${field}.

My background reflects this direction: ${background}. These experiences gave me both the technical foundation and the persistence needed to take on ambitious, open-ended problems — qualities I intend to bring to ${program}.

I am confident that the combination of my preparation and genuine enthusiasm for ${field} make me a strong fit for this program, and I look forward to contributing to and learning from your academic community.

— This is a placeholder draft generated by a template, not a real AI model.
Connect a real generation backend to produce a personalized version. —`;
}

function buildLorDraft(values: DraftFormValues): string {
  const studentName = pick(values, "studentName", "the applicant");
  const relationship = pick(values, "relationship", "their academic advisor");
  const program = pick(values, "program", "their target program");
  const strengths = pickSentence(
    values,
    "strengths",
    "describe specific strengths, achievements and examples here"
  );

  return `Dear Admissions Committee,

It is my pleasure to write this letter in support of ${studentName}'s application to ${program}. I have known ${studentName} in my capacity as ${relationship}, which has given me a close view of their academic ability and character.

Among their many strengths: ${strengths}. These qualities consistently set ${studentName} apart from their peers, and I am confident they will continue to excel in a more advanced academic environment.

I recommend ${studentName} to ${program} without reservation and am happy to be contacted for any further detail.

Sincerely,
[Your name]
${relationship}

— This is a placeholder draft generated by a template, not a real AI model.
Connect a real generation backend to produce a personalized version. —`;
}
