export { COUNTRIES, MAJORS };
export type { Country, Major };

export type SubScores = {
  mentorship: number;
  funding: number;
  workLifeBalance: number;
  publishing: number;
};

export type LabReview = {
  id: string;
  role: string;
  date: string;
  body: string;
};

export type Position = "PhD" | "MS" | "Research assistant" | "Postdoc";
export type Accepting = "Open" | "Limited" | "Closed";

export type Publication = { title: string; venue: string; year: number };

export type Lab = {
  id: string;
  professor: string;
  title: string;
  labName: string;
  university: string;
  department: string;
  country: Country;
  field: Major;
  researchAreas: string[];
  accepting: Accepting;
  acceptingNote: string;
  positions: Position[];
  labSize: number;
  /** Bangladeshi students and alumni who have worked in the lab. */
  bdAlumni: number;
  hIndex: number;
  subScores: SubScores;
  fundingInfo: string;
  description: string;
  requirements: string[];
  publications: Publication[];
  contactTip: string;
  reviews: LabReview[];
};

type LabInput = Omit<Lab, "subScores" | "publications" | "reviews"> & {
  /** mentorship, funding, work-life balance, publishing */
  scores: [number, number, number, number];
  pubs: [string, string, number][];
  reviews: [string, string, string][];
};

function lab({ scores, pubs, reviews, ...l }: LabInput): Lab {
  const [mentorship, funding, workLifeBalance, publishing] = scores;
  return {
    ...l,
    subScores: { mentorship, funding, workLifeBalance, publishing },
    publications: pubs.map(([title, venue, year]) => ({ title, venue, year })),
    reviews: reviews.map(([role, date, body], i) => ({ id: `r${i + 1}`, role, date, body })),
  };
}

