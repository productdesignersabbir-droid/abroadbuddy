function difficultyFor(acceptanceRate: number): Difficulty {
  if (acceptanceRate <= 15) return "Highly Competitive";
  if (acceptanceRate <= 45) return "Competitive";
  return "Moderate";
}

export type UniInput = Omit<
  University,
  "difficulty" | "imageSrc" | "imageAlt" | "tuitionMin" | "tuitionMax" | "intakes" | "toefl"
> & {
  tuition: [number, number];
  intakes?: string[];
  toefl?: number;
  /** Use the destination city photo instead of a campus photo. */
  cityPhoto?: boolean;
};

const seenCountries = new Set<Country>();
let campusIndex = 0;

function uni({ tuition, intakes, toefl, cityPhoto, ...u }: UniInput): University {
  // The first university in each country shows its city; the rest rotate campus photos.
  const useCity = cityPhoto ?? !seenCountries.has(u.country);
  seenCountries.add(u.country);
  const city = CITY_PHOTOS[u.country];
  const [id, alt] =
    useCity && city ? city : CAMPUS_PHOTOS[campusIndex++ % CAMPUS_PHOTOS.length];
  return {
    ...u,
    tuitionMin: tuition[0],
    tuitionMax: tuition[1],
    intakes: intakes ?? COUNTRY_INFO[u.country].intakes,
    toefl: toefl ?? Math.round(u.ielts * 14 - 6),
    difficulty: difficultyFor(u.acceptanceRate),
    imageSrc: photo(id),
    imageAlt: alt,
  };
}

